def build_parser() -> argparse.ArgumentParser:
    """Construct the argument parser.

    Returns:
        The configured parser.
    """
    parser = argparse.ArgumentParser(
        prog="cca_synth",
        description=(
            "Calibrated synthesizer over structured multi-agent candidate "
            "records, with Shapley ablation, calibration, and governance."
        ),
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    subparsers = parser.add_subparsers(dest="command", required=True)

    simulate = subparsers.add_parser("simulate", help="write a synthetic corpus to JSONL")
    add_config_cli_arguments(simulate)
    simulate.add_argument("--out", type=str, default=None, help="Destination JSONL path.")
    simulate.add_argument("--n-items", type=int, default=None, help="Number of items.")
    simulate.set_defaults(func=cmd_simulate)

    train = subparsers.add_parser("train", help="train the synthesizer")
    add_config_cli_arguments(train)
    add_resume_cli_arguments(train)
    train.set_defaults(func=cmd_train)

    evaluate = subparsers.add_parser("evaluate", help="calibrate, evaluate, probe robustness")
    add_config_cli_arguments(evaluate)
    evaluate.add_argument("--checkpoint", type=str, default=None, help="Checkpoint to load.")
    evaluate.set_defaults(func=cmd_evaluate)

    ablate = subparsers.add_parser("ablate", help="coalition sweep and Shapley analysis")
    add_config_cli_arguments(ablate)
    ablate.add_argument("--checkpoint", type=str, default=None, help="Checkpoint to load.")
    ablate.set_defaults(func=cmd_ablate)

    report = subparsers.add_parser("report", help="render REPORT.md from run artifacts")
    add_config_cli_arguments(report)
    report.set_defaults(func=cmd_report)

    everything = subparsers.add_parser("all", help="train, evaluate, ablate, report")
    add_config_cli_arguments(everything)
    add_resume_cli_arguments(everything)
    everything.add_argument("--checkpoint", type=str, default=None, help="Checkpoint to load.")
    everything.set_defaults(func=cmd_all)

    return parser


def add_resume_cli_arguments(parser: argparse.ArgumentParser) -> None:
    """Attach the training-resume flags to a subparser.

    Args:
        parser: Subparser to extend.
    """
    parser.add_argument(
        "--resume",
        nargs="?",
        const="auto",
        default=None,
        metavar="PATH",
        help=(
            "Resume training from a checkpoint, restoring optimiser, scheduler, "
            "scaler, EMA, step counter, and coalition RNG. Bare --resume uses "
            "the run's last.pt."
        ),
    )
    parser.add_argument(
        "--resume-ignore-config",
        action="store_true",
        help="Permit resuming when the checkpoint's config hash differs (warns).",
    )


def main(argv: Optional[Sequence[str]] = None) -> int:
    """Parse arguments and dispatch, guaranteeing process-group cleanup.

    Args:
        argv: Argument vector; defaults to ``sys.argv[1:]``.

    Returns:
        Process exit code.
    """
    args = build_parser().parse_args(argv)
    try:
        return int(args.func(args))
    finally:
        cleanup_distributed()


if __name__ == "__main__":
    sys.exit(main())
