@torch.no_grad()
def write_audit_records(
    trainer: Trainer,
    split: str,
    abstain_threshold: Optional[float],
    path: str,
    cfg: Config,
) -> Dict[str, Any]:
    """Emit the structured decision record for each item.

    This is the replacement for the PDF's "cognitive audit trail".  It contains
    the final answer, each agent's answer and recalibrated confidence, each
    claim's evidence status, the accept/reject decision, and the discrete rule
    that produced it -- and it contains **no chain-of-thought, no prompts, and
    no free text**, which is precisely the substitution
    ``ETHICS_AND_DATA_GOVERNANCE.md`` requires.  :class:`utils.AuditRecordWriter`
    raises on any field outside the allowlist, so a future edit cannot quietly
    reintroduce hidden reasoning.

    Args:
        trainer: Trained trainer.
        split: Split to record.
        abstain_threshold: Selective-prediction threshold.
        path: Destination JSONL path.
        cfg: Root configuration.

    Returns:
        A summary with the record count and destination.
    """
    device = trainer.device
    model = trainer.raw_model
    model.eval()
    timestamp = _dt.datetime.now(_dt.timezone.utc).isoformat()
    coalition_string = "1" * N_ROLES

    written = 0
    with AuditRecordWriter(
        path, enabled=cfg.eval.write_audit_records, max_records=cfg.eval.max_audit_records
    ) as writer:
        if not writer.enabled:
            return {"written": 0, "path": None, "enabled": False}

        for raw_batch in trainer.loaders[split]:
            if written >= cfg.eval.max_audit_records:
                break
            batch = move_batch_to_device(raw_batch, device)
            batch_size = batch["present"].shape[0]
            coalition = torch.ones(batch_size, N_ROLES, device=device)
            predictions = model.predict(batch, coalition, abstain_threshold=abstain_threshold)

            claim_accept = predictions.get("claim_accept_logit")
            claim_rules = predictions.get("claim_rule_logits")
            accept_probability = (
                torch.sigmoid(claim_accept).cpu().numpy() if claim_accept is not None else None
            )
            rule_index = (
                claim_rules.argmax(dim=-1).cpu().numpy() if claim_rules is not None else None
            )

            present = batch["present"].cpu().numpy()
            vote = batch["vote"].cpu().numpy()
            role_conf = batch["role_conf"].cpu().numpy()
            abstain_flags = batch["abstain"].cpu().numpy()
            role_scalars = batch["role_scalars"].cpu().numpy()
            flags = batch["flags"].cpu().numpy()
            claim_status = batch["claim_status"].cpu().numpy()
            claim_mask = batch["claim_mask"].cpu().numpy()
            claim_source = batch["claim_has_source"].cpu().numpy()
            cost = batch["cost"].cpu().numpy()
            recalibrated = predictions["recalibrated_confidence"].float().cpu().numpy()
            prediction = predictions["prediction"].cpu().numpy()
            confidence = predictions["confidence"].float().cpu().numpy()
            abstained = predictions["abstain"].cpu().numpy()
            benchmark_ids = batch["benchmark_id"].cpu().numpy()

            for i in range(batch_size):
                if written >= cfg.eval.max_audit_records:
                    break
                agent_records: List[Dict[str, Any]] = []
                unresolved = 0
                for r, role in enumerate(ROLES):
                    if not present[i, r]:
                        agent_records.append(
                            {
                                "agent_slot": int(r),
                                "agent_role": role,
                                "agent_present": False,
                                "agent_answer_option": -1,
                                "agent_abstained": True,
                                "failure_flags": [
                                    FAILURE_FLAGS[f]
                                    for f in range(len(FAILURE_FLAGS))
                                    if flags[i, r, f] > 0
                                ],
                                "claims": [],
                            }
                        )
                        continue

                    answer = int(vote[i, r].argmax()) if vote[i, r].sum() > 0 else -1
                    claims: List[Dict[str, Any]] = []
                    for c in range(claim_status.shape[2]):
                        if not claim_mask[i, r, c]:
                            continue
                        accepted = (
                            bool(accept_probability[i, r, c] >= 0.5)
                            if accept_probability is not None
                            else None
                        )
                        rule = (
                            ADJUDICATION_RULES[int(rule_index[i, r, c])]
                            if rule_index is not None
                            else None
                        )
                        if rule == "deferred_conflict_unresolved":
                            unresolved += 1
                        claims.append(
                            {
                                "claim_index": int(c),
                                "claim_evidence_status": EVIDENCE_STATUSES[
                                    int(min(claim_status[i, r, c], len(EVIDENCE_STATUSES) - 1))
                                ],
                                "claim_has_source": bool(claim_source[i, r, c] > 0.5),
                                "claim_accepted": accepted,
                                "claim_rule": rule,
                                "claim_accept_probability": (
                                    float(accept_probability[i, r, c])
                                    if accept_probability is not None
                                    else None
                                ),
                            }
                        )

                    agent_records.append(
                        {
                            "agent_slot": int(r),
                            "agent_role": role,
                            "agent_present": True,
                            "agent_answer_option": answer,
                            "agent_declared_confidence": float(role_conf[i, r]),
                            "agent_recalibrated_confidence": float(recalibrated[i, r]),
                            "agent_abstained": bool(abstain_flags[i, r] > 0.5),
                            "counterevidence_count": int(
                                round(float(np.expm1(role_scalars[i, r, 2] * 3.0)))
                            ),
                            "failure_flags": [
                                FAILURE_FLAGS[f]
                                for f in range(len(FAILURE_FLAGS))
                                if flags[i, r, f] > 0
                            ],
                            "claims": claims,
                            "output_tokens": int(round(float(np.expm1(cost[i, r, 0] * 10.0)))),
                            "latency_ms": float(np.expm1(cost[i, r, 1] * 10.0)),
                            "cost_usd": float(np.expm1(cost[i, r, 2] * 10.0) / 1e4),
                        }
                    )

                writer.write(
                    {
                        "item_id": batch["item_id"][i],
                        "benchmark": BENCHMARKS[int(benchmark_ids[i])],
                        "provenance": cfg.data.provenance,
                        "run_id": cfg.run_id,
                        "config_hash": config_hash(cfg),
                        "timestamp_utc": timestamp,
                        "coalition": coalition_string,
                        "final_answer_option": int(prediction[i]),
                        "abstained": bool(abstained[i]),
                        "synthesizer_confidence": float(confidence[i]),
                        "unresolved_conflicts": int(unresolved),
                        "agent_records": agent_records,
                    }
                )
                written += 1

    return {"written": written, "path": path, "enabled": True}


