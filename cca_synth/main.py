"""Command-line entry point for ``cca_synth``.

Subcommands
-----------

``simulate``
    Write a synthetic candidate-record corpus to JSONL.

``train``
    Train the calibrated synthesiser under coalition dropout.

``evaluate``
    Fit post-hoc calibration on the calibration split, evaluate the synthesiser
    and every non-learned comparator on the test split, run the robustness
    battery, and emit audit records.

``ablate``
    Sweep all ``2**6 = 64`` coalitions, compute Shapley values with bootstrap
    intervals, and run the FDR-corrected agent-by-benchmark family.

``report``
    Assemble the artifacts of a run into a Markdown report.

``all``
    ``train`` then ``evaluate`` then ``ablate`` then ``report``.

Every command prints the mandatory disclaimer and the data-provenance banner.
Runs on simulated data are marked as such in every artifact; ``--strict-real``
refuses to start unless real logged records were supplied.

Single process::

    python main.py all --config configs/default.json

Multi-GPU::

    torchrun --nproc_per_node=4 main.py train --config configs/default.json
"""

