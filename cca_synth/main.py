def run_directory(cfg: Config) -> str:
    """Return (and create) this run's artifact directory.

    Args:
        cfg: Root configuration.

    Returns:
        Absolute path to ``<output_dir>/<run_id>``.
    """
    path = os.path.abspath(os.path.join(cfg.train.output_dir, cfg.run_id))
    if is_main_process():
        os.makedirs(path, exist_ok=True)
    return path


def print_banner(cfg: Config, logger: Any) -> None:
    """Emit the disclaimer and the provenance warning.

    A simulated run is announced loudly and repeatedly.  The PDF reports no
    experiments; nothing produced from simulated records is evidence about CCA,
    and the banner is the first line of defence against a plot from this repo
    being pasted into a paper.

    Args:
        cfg: Root configuration.
        logger: Logger to write to.
    """
    logger.info("=" * 78)
    logger.info("CCA calibrated synthesizer | run_id=%s", cfg.run_id)
    logger.info("config_hash=%s", config_hash(cfg)[:16])
    logger.info("DISCLAIMER: %s", DISCLAIMER)
    if cfg.data.provenance != "real":
        logger.info("-" * 78)
        logger.info("DATA PROVENANCE: SIMULATED")
        logger.info(
            "These records were generated by dataset.simulate_records. They "
            "validate the pipeline, not the CCA hypothesis. No number produced "
            "from this run is an empirical result about CCA. Use --strict-real "
            "to forbid this mode."
        )
        logger.info("-" * 78)
    else:
        logger.info("DATA PROVENANCE: REAL (%s)", cfg.data.records_path)
    logger.info("=" * 78)


def setup_run(args: argparse.Namespace) -> Tuple[Config, DistState, Any]:
    """Build the configuration, seed everything, and initialise distribution.

    Args:
        args: Parsed CLI arguments.

    Returns:
        Tuple ``(cfg, dist_state, logger)``.
    """
    cfg = build_config_from_args(args)
    dist_state = setup_distributed(cfg)
    seed_everything(cfg.train.seed, deterministic=cfg.train.deterministic, rank=dist_state.rank)

    directory = run_directory(cfg)
    logger = get_logger(log_file=os.path.join(directory, "run.log"))
    print_banner(cfg, logger)
    logger.info(
        "device=%s world_size=%d amp=%s", dist_state.device, dist_state.world_size, cfg.train.amp
    )
    if is_main_process():
        save_config(cfg, os.path.join(directory, "config.json"))
    return cfg, dist_state, logger


def build_trainer(
    cfg: Config, dist_state: DistState, logger: Any
) -> Tuple[Trainer, Dict[str, Any]]:
    """Construct loaders, model, and trainer.

    Args:
        cfg: Root configuration.
        dist_state: Distributed state.
        logger: Logger.

    Returns:
        Tuple ``(trainer, data_summary)``.
    """
    loaders, summary = build_dataloaders(cfg, dist_state)
    cfg.validate()  # provenance is finalised by the loader; re-check strict_real
    model = build_model(cfg)
    logger.info(
        "model parameters: %s | splits: %s",
        f"{model.num_parameters():,}",
        summary["split_sizes"],
    )
    trainer = Trainer(cfg, model, loaders, dist_state, logger=logger)
    return trainer, summary


